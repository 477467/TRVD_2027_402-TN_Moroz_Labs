-- Лабораторна робота №4: ролі, користувачі та refresh-токени

CREATE TABLE roles (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
INSERT INTO roles (name) VALUES ('admin'), ('operator');

CREATE TABLE users (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username      text NOT NULL UNIQUE,
  password_hash text NOT NULL,            -- хеш bcrypt із сіллю, пароль у відкритому вигляді не зберігається
  role_id       integer NOT NULL REFERENCES roles(id),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE refresh_tokens (
  id         uuid PRIMARY KEY,            -- збігається з claim jti у refresh-токені
  user_id    uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash text NOT NULL,               -- SHA-256 від токена; сам токен у БД не зберігається
  expires_at timestamptz NOT NULL,
  revoked    boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens(user_id);
