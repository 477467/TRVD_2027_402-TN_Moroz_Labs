-- Схема БД за ER-діаграмою з лабораторної роботи №2 (нормалізована до 3НФ)

CREATE TABLE cities (
  name   text PRIMARY KEY,
  region text NOT NULL,
  lat    numeric(9,6) NOT NULL,
  lon    numeric(9,6) NOT NULL
);

CREATE TABLE crimes (
  id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL UNIQUE
);

CREATE TABLE persons (
  id          text PRIMARY KEY CHECK (id ~ '^CP-[0-9]{3,}$'),
  name        text NOT NULL,
  surname     text NOT NULL,
  dob         text NOT NULL,
  address     text,
  city        text NOT NULL REFERENCES cities(name),
  status      text NOT NULL,
  description text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_persons_city   ON persons(city);
CREATE INDEX idx_persons_status ON persons(status);

CREATE TABLE person_crimes (
  person_id text    NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
  crime_id  integer NOT NULL REFERENCES crimes(id),
  PRIMARY KEY (person_id, crime_id)
);

CREATE TABLE staff (
  id         text PRIMARY KEY,
  name       text NOT NULL,
  rank       text NOT NULL,
  position   text NOT NULL,
  department text NOT NULL,
  cases      integer NOT NULL DEFAULT 0
);

CREATE TABLE documents (
  id             text PRIMARY KEY,
  title          text NOT NULL,
  type           text NOT NULL,
  classification text NOT NULL,
  content        text,
  person_id      text REFERENCES persons(id),
  author_id      text REFERENCES staff(id)
);

CREATE TABLE cyber_attacks (
  id       text PRIMARY KEY,
  type     text NOT NULL,
  target   text NOT NULL,
  severity text NOT NULL,
  date     date NOT NULL,
  city     text REFERENCES cities(name)
);

CREATE TABLE city_news (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city     text NOT NULL REFERENCES cities(name),
  date     date NOT NULL,
  headline text NOT NULL
);
